"""Five deterministic *provisional* contact-observation protocols.

These are capture instructions, not gameplay proofs. No genuine iOS trace is
generated by this module. All source measurements remain private.
"""
from __future__ import annotations

import argparse
from collections import Counter
import json
from pathlib import Path

from .contact_trace_audit import (
    _parse_capture, compare_contact_traces, MAX_BYTES,
)
from .frame_alignment import _private_path

FPS = 60
# Horizontal spans are half-open [start,end). Jump is a one-frame button edge.
# Preconditions are instructions for a private operator, NOT automatically
# verified by this code or guaranteed to hold in the original mobile game.
SCENARIOS = {
    "landing": {
        "frames": 120,
        "horizontal_spans": (),
        "jump_frames": (),
        "required_transitions": (("airborne", "floor"),),
        "required_contacts": ("floor",),
        "precondition": "Start above an observed flat candidate surface, not grounded",
    },
    "jump": {
        "frames": 150,
        "horizontal_spans": (),
        "jump_frames": (15,),
        "required_transitions": (("floor", "airborne"),
                                 ("airborne", "floor")),
        "required_contacts": ("floor", "airborne"),
        "precondition": "Begin grounded with enough clear overhead and landing room",
    },
    "wall": {
        "frames": 120,
        "horizontal_spans": ((10, 90, 1),),
        "jump_frames": (),
        "required_transitions": (),
        "required_contacts": ("wall",),
        "precondition": "Position right of empty runway, left of a candidate wall",
    },
    "ceiling": {
        "frames": 130,
        "horizontal_spans": (),
        "jump_frames": (12,),
        "required_transitions": (),
        "required_contacts": ("ceiling",),
        "precondition": "Begin grounded directly below a reachable candidate ceiling",
    },
    "ledge": {
        "frames": 130,
        "horizontal_spans": ((10, 120, 1),),
        "jump_frames": (),
        "required_transitions": (("floor", "airborne"),),
        "required_contacts": ("floor", "airborne"),
        "precondition": "Begin grounded sufficiently near a candidate platform edge",
    },
}
MAX_SUITE_FILE = 5 * MAX_BYTES + 100000


def describe_scenarios() -> dict:
    """Public capture protocol; never claims those events are observed."""
    return {
        "protocol_version": 1,
        "nominal_fps": FPS,
        "scenario_count": len(SCENARIOS),
        "scenarios": {
            name: {
                "frames": data["frames"],
                "horizontal_spans_half_open": [
                    list(span) for span in data["horizontal_spans"]],
                "jump_edge_frames": list(data["jump_frames"]),
                "required_contact_states": list(data["required_contacts"]),
                "required_contact_transitions": [
                    list(pair) for pair in data["required_transitions"]],
                "manual_initial_condition": data["precondition"],
            } for name, data in SCENARIOS.items()
        },
        "iOS_contact_capture_available": False,
        "original_gameplay_fidelity_verified": False,
    }


def scripted_controls(scenario_id: str) -> tuple[tuple[int, bool], ...]:
    """Generate frame-addressed logical controls, independent of button layout."""
    if type(scenario_id) is not str or scenario_id not in SCENARIOS:
        raise ValueError("unsupported contact observation scenario")
    protocol = SCENARIOS[scenario_id]
    script = [(0, False) for _ in range(protocol["frames"])]
    for start, end, axis in protocol["horizontal_spans"]:
        for i in range(start, end):
            script[i] = (axis, script[i][1])
    for frame in protocol["jump_frames"]:
        script[frame] = (script[frame][0], True)
    return tuple(script)


def _observed_events(records: list[tuple]) -> tuple[Counter, Counter]:
    states = Counter(r[2] for r in records)
    transitions = Counter(
        (a[2], b[2]) for a, b in zip(records, records[1:])
        if a[2] != b[2])
    return states, transitions


def validate_scenario_trace(data: dict, *,
                            max_position_error_units: float = 1.0,
                            max_contact_mismatches: int = 0) -> dict:
    """Check an explicitly labeled pair of captures against one protocol.

    Failing event coverage is a blocker, not a fabricated 'pass'. Matching
    events still do not authenticate that frames came from the original game.
    """
    if not isinstance(data, dict):
        raise ValueError("expected paired-capture report")
    scenario_id = data.get("scenario_id")
    if type(scenario_id) is not str or scenario_id not in SCENARIOS:
        raise ValueError("unsupported contact observation scenario")
    if data.get("fps") != FPS or type(data.get("fps")) is not int:
        raise ValueError("capture FPS differs from provisional protocol")
    protocol = SCENARIOS[scenario_id]
    expected = scripted_controls(scenario_id)
    observed = {}
    for key, platform in (("reference", "ios"), ("candidate", "switch")):
        capture = _parse_capture(data.get(key), platform)
        if len(capture["records"]) != len(expected):
            raise ValueError("capture frame count differs from scenario protocol")
        for i, (axis, jump, _, _) in enumerate(capture["records"]):
            if (axis, jump) != expected[i]:
                raise ValueError(f"{platform} input differs from scripted frame {i}")
        states, transitions = _observed_events(capture["records"])
        missing_states = [state for state in protocol["required_contacts"]
                          if states[state] == 0]
        missing_transitions = [list(pair) for pair in protocol[
            "required_transitions"] if transitions[pair] == 0]
        observed[platform] = {
            "capture_id": capture["id"],
            "evidence_kind": capture["evidence"],
            "required_contacts_observed": not missing_states,
            "missing_contact_states": missing_states,
            "missing_transitions": missing_transitions,
            "required_transitions_observed": not missing_transitions,
            "unknown_contact_frames": states["unknown"],
        }

    comparison = compare_contact_traces(
        data, max_position_error_units=max_position_error_units,
        max_contact_mismatches=max_contact_mismatches)
    contract_satisfied = (
        comparison["numeric_agreement_under_supplied_scale"]
        and all(row["required_contacts_observed"]
                and row["required_transitions_observed"]
                and row["unknown_contact_frames"] == 0
                for row in observed.values()))
    return {
        "scenario_id": scenario_id,
        "protocol_version": 1,
        "frames": len(expected),
        "nominal_fps": FPS,
        "per_platform": observed,
        "comparison": comparison,
        "protocol_and_numeric_consistency_on_supplied_records": contract_satisfied,
        "both_captures_independently_authenticated": False,
        "original_ios_contact_semantics_verified": False,
        "original_gameplay_physics_verified": False,
        "automatic_collision_export_permitted": False,
        "interpretation": (
            "Matched scripted inputs and human-labeled events on supplied "
            "records. This cannot authenticate original-game footage, true "
            "contact categories, calibration or physical fidelity."
        ),
    }


def validate_scenario_suite(data: dict, *,
                            max_position_error_units: float = 1.0,
                            max_contact_mismatches: int = 0) -> dict:
    """Require one distinct paired trace for every predefined protocol."""
    if not isinstance(data, dict) or not isinstance(data.get("traces"), list):
        raise ValueError("suite must contain a list of five paired traces")
    traces = data["traces"]
    if len(traces) != len(SCENARIOS):
        raise ValueError("suite requires exactly five paired scenarios")
    if any(not isinstance(trace, dict) for trace in traces):
        raise ValueError("invalid suite trace item")
    names = [trace.get("scenario_id") for trace in traces]
    if (any(type(name) is not str for name in names)
            or len(set(names)) != len(SCENARIOS)
            or set(names) != set(SCENARIOS)):
        raise ValueError("suite must include each required scenario once")
    reports = {}
    capture_ids = set()
    for trace in traces:
        name = trace["scenario_id"]
        report = validate_scenario_trace(
            trace, max_position_error_units=max_position_error_units,
            max_contact_mismatches=max_contact_mismatches)
        for side in ("ios", "switch"):
            capture_id = report["per_platform"][side]["capture_id"]
            if capture_id in capture_ids:
                raise ValueError("suite reuses a capture identifier")
            capture_ids.add(capture_id)
        reports[name] = report
    return {
        "protocol_version": 1,
        "scenario_count": len(SCENARIOS),
        "scenarios": {name: reports[name] for name in SCENARIOS},
        "numerical_and_event_contracts_all_met": all(
            report["protocol_and_numeric_consistency_on_supplied_records"]
            for report in reports.values()),
        "real_original_ios_traces_authenticated": False,
        "original_gameplay_physics_verified": False,
        "automatic_collision_export_permitted": False,
    }


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--describe", action="store_true",
                        help="print fictional observation protocol without reading an IPA")
    parser.add_argument("--traces", type=Path)
    parser.add_argument("--out", type=Path)
    parser.add_argument("--suite", action="store_true")
    args = parser.parse_args(argv)
    if args.describe:
        if args.traces is not None or args.out is not None or args.suite:
            parser.error("--describe cannot be combined with trace inputs")
        print(json.dumps(describe_scenarios(), indent=2))
        return 0
    if args.traces is None or args.out is None:
        parser.error("provide --traces and --out or use --describe")
    source, target = _private_path(args.traces), _private_path(args.out)
    if source == target:
        raise ValueError("trace input and summary must be distinct files")
    if source.stat().st_size > (MAX_SUITE_FILE if args.suite else MAX_BYTES):
        raise ValueError("private trace input exceeds size limit")
    data = json.loads(source.read_text(encoding="utf-8"))
    result = (validate_scenario_suite(data) if args.suite
              else validate_scenario_trace(data))
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n",
                      encoding="utf-8")
    print("Checked provisional capture protocol; iOS evidence remains unverified.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
