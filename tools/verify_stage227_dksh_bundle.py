"""Stage227: bounded DKSH control/code bundle inspector (public synthetic-only).

Verifies self-consistent deko3d shader files generated by uam; this does
not execute a shader or prove texture sampling, frame capture or GPU parity.
Based on the six-field DKSH header consumed by the public deko3d samples.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import struct

HEADER = struct.Struct("<6I")
MAX_DKSH_BYTES = 1024 * 1024
MAGIC = int.from_bytes(b"DKSH", "little")


class DKSHValidationError(ValueError):
    """Malformed, truncated or unsupported shader bundle."""


def inspect_dksh(content: bytes, *, shader_stage: str) -> dict:
    if shader_stage not in ("vertex", "fragment"):
        raise DKSHValidationError("Expected a known vertex or fragment stage")
    if type(content) is not bytes or not HEADER.size <= len(content) <= MAX_DKSH_BYTES:
        raise DKSHValidationError("DKSH file must be a bounded nonempty byte buffer")
    magic, header_size, control_size, code_size, programs_offset, num_programs = (
        HEADER.unpack_from(content)
    )
    if magic != MAGIC:
        raise DKSHValidationError("Missing the actual DKSH magic")
    if not HEADER.size <= header_size <= control_size <= len(content):
        raise DKSHValidationError("Invalid DKSH control/header byte ranges")
    if code_size == 0 or code_size > len(content) - control_size:
        raise DKSHValidationError("Missing or truncated DKSH machine-code region")
    if not header_size <= programs_offset < control_size:
        raise DKSHValidationError("Invalid DKSH program table offset")
    if not 1 <= num_programs <= 16:
        raise DKSHValidationError("Unsupported DKSH program count")
    return {
        "classification": "compiled_synthetic_deko3d_dksh_bundle",
        "shader_stage": shader_stage,
        "byte_size": len(content),
        "header_size": header_size,
        "control_size": control_size,
        "code_size": code_size,
        "program_count": num_programs,
        "binary_magic_verified": True,
        "source_game_assets_included": False,
        "gpu_shader_executed": False,
        "gpu_texture_sampling_verified": False,
        "gpu_pixel_readback_verified": False,
        "original_ios_runtime_pixel_parity_verified": False,
    }


def check_pair(vertex_path: Path, fragment_path: Path) -> dict:
    first = vertex_path.read_bytes()
    second = fragment_path.read_bytes()
    if first == second:
        raise DKSHValidationError("Vertex and fragment programs cannot be identical")
    return {
        "shader_count": 2,
        "stages": [
            inspect_dksh(first, shader_stage="vertex"),
            inspect_dksh(second, shader_stage="fragment"),
        ],
        "original_game_resources_used": False,
        "hardware_gpu_sampling_verified": False,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("vertex", type=Path)
    parser.add_argument("fragment", type=Path)
    args = parser.parse_args()
    print(json.dumps(check_pair(args.vertex, args.fragment), indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
